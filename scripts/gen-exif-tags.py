#!/usr/bin/env python3
"""Generate media/exiftags.go from Pillow's EXIF tag tables.

bundle-python names EXIF tags with Pillow's ExifTags.TAGS and GPSTAGS, and
Pillow decides from TiffTags whether a value is a scalar or a list. The Go
media package uses the same tables, so both tools write the same MEDIA.json.

    pip install pillow && scripts/gen-exif-tags.py > media/exiftags.go && gofmt -w media/exiftags.go
"""
import PIL
from PIL import ExifTags, TiffTags

EXIF_GROUP, GPS_GROUP = 0x8769, 0x8825


def length(tag, group):
    value = TiffTags.lookup(tag, group).length
    return -1 if value is None else value


def table(name, comment, names, group):
    print(f"// {comment}")
    print(f"var {name} = map[uint16]exifTag{{")
    for tag in sorted(names):
        print(f"\t0x{tag:04X}: {{{names[tag]!r}, {length(tag, group)}}},".replace("'", '"'))
    print("}\n")


print(f"// Code generated by scripts/gen-exif-tags.py from Pillow {PIL.__version__}; DO NOT EDIT.\n")
print("package media\n")
table("mainTags", "mainTags are the tags of IFD0, with their Pillow length in IFD0.", ExifTags.TAGS, None)
table("exifTags", "exifTags are the tags of the Exif IFD, with their Pillow length there.", ExifTags.TAGS, EXIF_GROUP)
table("gpsTags", "gpsTags are the tags of the GPS IFD.", ExifTags.GPSTAGS, GPS_GROUP)
